"""
Startup banner — termcn BigText-style ASCII art, Textual-native.

Renders block-letter banners (5 rows high) with zero dependencies.
Covers A-Z, 0-9 and a few symbols; anything else renders blank.
"""

from __future__ import annotations

# "#" = filled cell, "." = empty. Each glyph is 5 wide, 5 tall.
